"""Versioned run artifacts.

Every training run writes to ``artifacts/<run_id>/``:

    config.yaml            exact (merged) configuration used
    run.log                full log of the run
    data_report.json       raw-data validation warnings and cleaning counts, data file SHA-256
    metrics/*.csv|json     CV results, test results, comparisons, sensitivity, lift, importance
    predictions/*.csv      out-of-fold and test probabilities (for reproducible reports)
    models/<name>.joblib   every tuned model
    model.joblib           the selected model (preprocessing + estimator)
    model_card.json        what the model is, how it was chosen, its threshold, metrics and versions
    plots/*.png

``artifacts/LATEST`` holds the id of the most recent successful run, so the CLI and
the report notebook can find it without symlinks (which Windows handles poorly).
"""

from __future__ import annotations

import json
import logging
import platform
from datetime import datetime
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
import yaml

logger = logging.getLogger(__name__)


def _jsonable(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, (pd.Timestamp, datetime)):
        return o.isoformat()
    if isinstance(o, Path):
        return str(o)
    raise TypeError(f"Not JSON serialisable: {type(o)}")


class RunArtifacts:
    def __init__(self, root: str | Path, run_id: str | None = None):
        self.root = Path(root)
        self.run_id = run_id or datetime.now().strftime("%Y%m%d-%H%M%S")
        self.dir = self.root / self.run_id
        for sub in ["metrics", "predictions", "models", "plots"]:
            (self.dir / sub).mkdir(parents=True, exist_ok=True)

    @property
    def log_file(self) -> Path:
        return self.dir / "run.log"

    def path(self, *parts: str) -> Path:
        return self.dir.joinpath(*parts)

    def save_config(self, cfg: dict) -> None:
        clean = {k: v for k, v in cfg.items() if not k.startswith("_")}
        with open(self.path("config.yaml"), "w", encoding="utf-8") as f:
            yaml.safe_dump(clean, f, sort_keys=False)

    def save_json(self, name: str, obj) -> Path:
        p = self.path(name)
        p.write_text(json.dumps(obj, indent=2, default=_jsonable), encoding="utf-8")
        return p

    def save_table(self, name: str, df: pd.DataFrame, index: bool = True) -> Path:
        p = self.path("metrics", f"{name}.csv")
        df.to_csv(p, index=index)
        return p

    def save_predictions(self, name: str, df: pd.DataFrame) -> Path:
        p = self.path("predictions", f"{name}.csv")
        df.to_csv(p, index=False)
        return p

    def save_model(self, name: str, model) -> Path:
        p = self.path("models", f"{name}.joblib") if name != "model" else self.path("model.joblib")
        joblib.dump(model, p, compress=3)
        return p

    def export_summary(self, dest: str | Path) -> Path:
        """Copy the lightweight outputs (no models, no predictions) to a folder meant for version control.

        Models are too large for git (the random forest is ~66 MB) and are regenerated by training;
        the exported summary lets reviewers see exactly what the run produced.
        """
        import shutil
        dest = Path(dest)
        if dest.exists():
            shutil.rmtree(dest)
        dest.mkdir(parents=True)
        for name in ["config.yaml", "data_report.json", "model_card.json", "run.log"]:
            if self.path(name).exists():
                shutil.copy2(self.path(name), dest / name)
        for sub in ["metrics", "plots"]:
            shutil.copytree(self.path(sub), dest / sub)
        (dest / "RUN_ID").write_text(self.run_id, encoding="utf-8")
        logger.info("Exported run summary to %s", dest)
        return dest

    def mark_latest(self) -> None:
        (self.root / "LATEST").write_text(self.run_id, encoding="utf-8")
        logger.info("Run %s marked as latest", self.run_id)


def environment() -> dict:
    return {"python": platform.python_version(), "platform": platform.platform(),
            "scikit_learn": sklearn.__version__, "pandas": pd.__version__, "numpy": np.__version__}


def latest_run_dir(root: str | Path = "artifacts") -> Path:
    root = Path(root)
    marker = root / "LATEST"
    if not marker.exists():
        raise FileNotFoundError(f"No completed training run found in {root}/ (run: python main.py train)")
    run_dir = root / marker.read_text(encoding="utf-8").strip()
    if not (run_dir / "model.joblib").exists():
        raise FileNotFoundError(f"{run_dir} has no model.joblib; the run may have failed")
    return run_dir


def load_model(run_dir: str | Path) -> tuple[object, dict]:
    run_dir = Path(run_dir)
    model = joblib.load(run_dir / "model.joblib")
    card = json.loads((run_dir / "model_card.json").read_text(encoding="utf-8"))
    return model, card
